function testbit(v, b)
	local mask = 1 << b
	return (v & mask) == mask
end

if curremu == const.GMULATOR then
	u8 = mem.readbyte
	u16 = mem.readword
	w8 = mem.writebyte
	w16 = mem.writeword

	getregister = function(r) return emu.getregister(r) end
	setregister = function(r, v) emu.setregister(r, v) end

	callbackexec = Type.Exec
	callbackframe = Type.Frame
	addmemcallback = emu.memcallback
	addeventcallback = emu.eventcallback

	drawtext = function(x, y, text, format, fgcolor, bgcolor, fontsize)
		if format ~= "" then
			gui.drawtext(x, y, string.format(format, text), fgcolor, bgcolor, fontsize)
		else
			gui.drawtext(x, y, text, fgcolor, bgcolor, fontsize)
		end
	end

