function countbits(value)
	local count = 0
	if value & 0x10 > 0 then
		count = count + 1
	end
	if value & 0x20 > 0 then
		count = count + 1
	end
	return count
end

function drawitems()
	stats()

	if u8(const.GAMEPLAY) == 7 and u8(const.GAMEPLAY_SUB) == 5 and u8(0xc19f) == 0 then
		local rw = 7
		local rh = 7
local xoff = 0x11
local yoff =0x09
		for k, value in pairs(items_d800) do
			local x = ((((value[1] & 0x0f) << 4) >> 1) & 0x78) + xoff
			local y = ((value[1] >> 1) & 0x78) + yoff
			local v = u8(const.MAP_OW + value[2])
			if v & value[3] ~= value[3] then
				drawrect(x, y, rw, rh, 0x00ff00)
			end
		end

		for k, value in pairs(items_d900) do
			local x = ((((value[1] & 0x0f) << 4) >> 1) & 0x78) + xoff
			local y = ((value[1] >> 1) & 0x78) + yoff
			local v = u8(const.MAP_UW1 + value[2])
			if v & value[3] ~= value[3] then
				drawrect(x, y, rw, rh, 0x00ff00)
			end
		end

		for k, value in pairs(items_da00) do
			local x = ((((value[1] & 0x0f) << 4) >> 1) & 0x78) + xoff
			local y = ((value[1] >> 1) & 0x78) + yoff
			local v = u8(const.MAP_UW2 + value[2])
			if v & value[3] ~= value[3] then
				drawrect(x, y, rw, rh, 0x00ff00)
			end
		end

		if u8(0xdb7d) == 0 then
			drawrect(((((0xf4 & 0x0f) << 4) >> 1) & 0x78) + xoff, ((0xf4 >> 1) & 0x78) + yoff, rw, rh, 0x00ff00)
		end

		for k, value in pairs(dungeon_counts) do
			local baseaddr = k < 6 and const.MAP_UW1 or const.MAP_UW2
			baseaddr = k == 0xff and const.MAP_COLOR or baseaddr
			local total = 0
			for _, i in pairs(value) do
				local v = u8(baseaddr + i)
				if v & 0x10 > 0 or v & 0x20 > 0 then
					total = total + 1
				end
			end
			dungeon_totals[k][1] = total
		end

		for k, value in pairs(dungeon_locations) do
			local x = ((((value & 0x0f) << 4) >> 1) & 0x78) + 0x12
			local y = ((value >> 1) & 0x78) + 0x09
			drawrect(x - 1, y, 8, 8, 0x000000, true)
			if dungeon_totals[k][1] == #dungeon_totals[k][2] then
				drawtext(x, y, k == 255 and 0 or k + 1, "%x", 0x4f00ffff)
			else
				drawtext(x, y, k == 255 and 0 or k + 1, "%x", 0x00ffff)
			end
		end
	end
end

function drawkeyrooms()
	if u8(0xdba5) == 1 then
		local dungeon_id = u8(0xfff7)
		local baseaddr = dungeon_id < 6 and const.MAP_UW1 or const.MAP_UW2
		baseaddr = dungeon_id == 0xff and const.MAP_COLOR or baseaddr
		for k, value in pairs(hidden_items_dungeons[dungeon_id]) do
			local v = u8(baseaddr + value[2])
			if v & 0x10 == 0 then
				w8(const.MAP_DUNGEON + value[1], 0xe7)
			end
		end
	end
end

function update()
	emu.log(string.format("%x %x", u8(0xdb54), u8(0xfff6)))
	emu.log(string.format("%x", u8(0xdbb4)))
end

function stats()
	local total = 0
	for k, value in pairs(items_d800) do
		local v = u8(const.MAP_OW + value[2])
		if v & 0x10 == value[3] then
			total = total + 1
		end
		if v & 0x20 == value[3] then
			total = total + 1
		end
	end

	for k, value in pairs(items_d900) do
		local v = u8(const.MAP_UW1 + value[2])
		if v & 0x10 == value[3] or v & 0x20 == value[3] then
			total = total + 1
		end
	end

	for k, value in pairs(items_da00) do
		local v = u8(const.MAP_UW2 + value[2])
		if v & value[3] == value[3] then
			if value[1] ~= 0x65 then
				total = total + 1
			end
		end
	end

	for k, value in pairs(dungeon_counts) do
		local baseaddr = k < 6 and const.MAP_UW1 or const.MAP_UW2
		baseaddr = k == 0xff and const.MAP_COLOR or baseaddr
		for _, i in pairs(value) do
			local v = u8(baseaddr + i)
			if v & 0x10 > 0 or v & 0x20 > 0 then
				total = total + 1
			end
		end
	end

	if u8(0xdb7d) ~= 0 then
		total = total + 1
	end

	local x, y
	if u8(const.GAMEPLAY) == 0x0c then
		x = 0
		y = 136
	else
		x = 120
		y = 0
	end

	drawtext(x, y, total, "%3d/227", 0x00ff00)
end

